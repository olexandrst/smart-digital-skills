#!/usr/bin/env bash
# Команда запуску для Azure App Service (Linux, Python).
# У налаштуваннях App Service → Configuration → Startup Command вкажіть:
#     bash startup.sh
#
# Скрипт робить дві речі: доводить базу до потрібної версії й запускає сервер.
set -e

cd "$(dirname "$0")"

# ---------------------------------------------------------------------------
# 1. Схема бази
#
# Міграції виконуються ТУТ, а не всередині застосунку. Різниця принципова:
# тут вони відпрацьовують рівно один раз на старт контейнера, ще до того, як
# з'явиться перший воркер. Усередині create_app() вони виконувались би в
# кожному воркері одночасно — на SQLite це гарантований конфлікт блокування.
#
# init_db розрізняє чисту базу (alembic upgrade head) і базу, створену до
# переходу на міграції (доганяє колонки й ставить штамп версії). Повторний
# запуск нічого не псує.
#
# RUN_MIGRATIONS_ON_START=0 вимикає крок, якщо ви накатуєте міграції вручну.
# ---------------------------------------------------------------------------
if [ "${RUN_MIGRATIONS_ON_START:-1}" = "1" ]; then
  echo "[startup] Міграції та довідники…"
  python -m scripts.init_db
fi

# ---------------------------------------------------------------------------
# 2. Початкові дані
#
#   auto (типово) — наповнити лише порожню базу. Саме те, що треба при
#                   безперервному розгортанні: контейнер перезапускається на
#                   кожен push, і беззастережний seed повертав би демо-
#                   користувачів, яких адміністратор перед тим видалив.
#   1             — виконувати завжди (скрипт ідемпотентний).
#   0             — ніколи; наповните вручну через SSH.
#
# Створює ролі, адміністратора (ADMIN_USERNAME / ADMIN_PASSWORD), трьох
# демо-користувачів і демо-каталог.
# ---------------------------------------------------------------------------
case "${SEED_ON_START:-auto}" in
  auto) echo "[startup] Початкові дані (лише якщо база порожня)…"
        python -m scripts.seed --if-empty ;;
  1)    echo "[startup] Початкові дані…"
        python -m scripts.seed ;;
  *)    : ;;
esac

# ---------------------------------------------------------------------------
# 3. Сервер
#
#   --workers 1   SQLite не тримає паралельний запис із кількох процесів.
#                 Паралелізм дають потоки, а не процеси. Кілька воркерів
#                 можна вмикати лише разом із переїздом на PostgreSQL.
#   --threads 4   Обробка кількох одночасних запитів в одному процесі.
#   --timeout 240 Відповіді LLM бувають довгими; стандартні 30 с їх обривають.
#                 Більше за 240 сенсу немає — Azure має власний ліміт близько
#                 230 с на HTTP-запит, і він не налаштовується.
#   $PORT         Порт, який App Service передає застосунку.
# ---------------------------------------------------------------------------
echo "[startup] gunicorn на порту ${PORT:-8000}"
exec gunicorn wsgi:app \
  --bind=0.0.0.0:${PORT:-8000} \
  --workers "${GUNICORN_WORKERS:-1}" \
  --threads "${GUNICORN_THREADS:-4}" \
  --timeout "${GUNICORN_TIMEOUT:-240}" \
  --access-logfile '-' \
  --error-logfile '-'
