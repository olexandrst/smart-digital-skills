"""Надсилання листів. Поки заглушка (фідбек тестування, п. 21).

Справжня відправка залежить від інфраструктури замовника: яка скринька і
яким способом (SMTP чи Microsoft Graph), ще не вирішено. Тому решта коду
знає лише одну точку входу, `send(to, subject, body)`. Зараз вона записує
лист у журнал застосунку й повертає False («не надіслано»). Коли спосіб
відправки з'явиться, зміниться тільки цей модуль.

Нічого важливого на лист не покладається: повідомлення, про які він
сповіщає, уже збережені в базі й видні в «Керуванні».
"""
import logging

log = logging.getLogger(__name__)


def send(to, subject, body):
    """Лист на адреси `to`. Повертає True, якщо лист справді надіслано."""
    recipients = sorted({a.strip() for a in (to or []) if a and a.strip()})
    if not recipients:
        return False
    log.info("Лист не надіслано (відправку ще не підключено). Кому: %s. Тема: %s\n%s",
             ", ".join(recipients), subject, body)
    return False
