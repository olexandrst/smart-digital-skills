#!/usr/bin/env bash
# Команда запуску для Azure App Service (Linux, Python).
# Вкажіть у налаштуваннях App Service → Configuration → Startup Command:
#     startup.sh
#
# Чому саме такі параметри:
#   --workers 1   SQLite не тримає паралельний запис із кількох процесів,
#                 а APScheduler стартує в КОЖНОМУ воркері — на двох воркерах
#                 тижневе скидання квот виконалося б двічі. Паралелізм дають
#                 потоки, а не процеси. Переходити на кілька воркерів можна
#                 лише разом із переїздом на PostgreSQL.
#   --threads 4   Обробка кількох одночасних запитів в одному процесі.
#   --timeout 240 Відповіді LLM бувають довгими; стандартні 30 с їх обривають.
#                 Більше за 240 ставити немає сенсу — Azure має власний ліміт
#                 близько 230 с на HTTP-запит, і він не налаштовується.
#   $PORT         Порт, який App Service передає застосунку.
set -e

exec gunicorn wsgi:app \
  --bind=0.0.0.0:${PORT:-8000} \
  --workers 1 \
  --threads 4 \
  --timeout 240 \
  --access-logfile '-' \
  --error-logfile '-'
